#!/usr/bin/env python3
"""Which shows are listed in tools/shows.json but have no files in british-tv/data/library.json?

These are the shows the TV is told to expect on a channel that the scraper has found nothing for, so On Demand
and the channel cannot show them. The list is what to hand to the scraper to look for (or to remove from
shows.json if they are not on archive.org at all).

    python3 tools/missing_shows.py            # print it
    python3 tools/missing_shows.py --write    # also write tools/missing-shows.md
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def norm(t):
    t = str(t or "").lower().replace("&", " and ").replace("'", "").replace("’", "")
    t = re.sub(r"[^a-z0-9]+", " ", t).strip()
    return re.sub(r"^the ", "", t)

lib = json.loads((ROOT / "british-tv/data/library.json").read_text(encoding="utf-8"))
sj = json.loads((ROOT / "tools/shows.json").read_text(encoding="utf-8"))
have = {norm(s["n"]) for s in lib["shows"]}
# shows the scraper has removed for good are not "missing": they are gone on purpose
rm = ROOT / "british-tv/data/removed-shows.json"
if rm.exists():
    for r in json.loads(rm.read_text(encoding="utf-8")).get("shows", []):
        have.add(norm(r.get("name", "")))
out = ["# Shows listed in tools/shows.json with no files in the library", "",
       "Generated by `tools/missing_shows.py`. Each is on a channel's list but the scraper has found nothing for it,",
       "so it cannot appear on the channel or in On Demand.", ""]
total = 0
for ch, v in sj.items():
    names = [n for n in v.get("shows", []) if norm(n) not in have]
    if not names:
        continue
    total += len(names)
    out.append(f"## {ch} ({len(names)} of {len(v.get('shows', []))} listed)")
    out.append("")
    out.append(", ".join(names))
    out.append("")
text = "\n".join(out)
print(text)
print(f"{total} listed shows have no files.", file=sys.stderr)
if "--write" in sys.argv:
    (ROOT / "tools/missing-shows.md").write_text(text + "\n", encoding="utf-8")
